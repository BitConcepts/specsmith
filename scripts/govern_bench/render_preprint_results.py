"""Render the release substitution summary as a generated LaTeX include."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

RELEASE_TASKS = {"T1", "T2", "T6", "T7", "T10", "T11", "T13", "T28"}
CODING_TASKS = RELEASE_TASKS - {"T6", "T7"}


def _latex(value: object) -> str:
    return (
        str(value)
        .replace("\\", r"\textbackslash{}")
        .replace("&", r"\&")
        .replace("%", r"\%")
        .replace("_", r"\_")
        .replace("#", r"\#")
    )


def _metric_row(system: str, metrics: dict[str, Any]) -> str:
    runs = int(metrics["runs"])
    correct = round(float(metrics["pass_rate"]) * runs)
    return (
        f"{_latex(system)} & {correct}/{runs} & "
        f"{float(metrics['tokens_per_correct_answer']):,.0f} & "
        f"{float(metrics['cost_of_pass']):.4f} \\\\"
    )


def _interval(values: list[float], *, percent: bool = False) -> str:
    low, high = (float(value) for value in values)
    if percent:
        return f"{low * 100:.1f}--{high * 100:.1f}\\,pp"
    return f"{low:.3f}--{high:.3f}"


def render_results(
    summary_path: Path,
    output_path: Path,
    *,
    workflow_id: str,
    commit_sha: str,
    coding_summary_path: Path | None = None,
) -> str:
    """Validate release evidence and render the exact paper table and claims."""
    payload = json.loads(summary_path.read_text(encoding="utf-8"))
    tasks = set(payload.get("tasks") or [])
    comparisons = payload.get("comparisons") or []
    if payload.get("schema") != "governancebench-model-comparison-v1":
        raise ValueError("unsupported comparison schema")
    if tasks != RELEASE_TASKS or len(comparisons) != 1:
        raise ValueError("preprint requires one complete substitution-release comparison")
    comparison = comparisons[0]
    inference = comparison.get("inference") or {}
    if int(inference.get("minimum_repetitions_per_task") or 0) < 10:
        raise ValueError("preprint release claims require at least ten repetitions per task")
    claims = inference.get("claims") or {}
    point = inference["point"]
    fixed = inference["fixed_suite_95_ci"]
    clustered = inference["task_cluster_95_ci"]
    lower = _latex(comparison["smaller_model"])
    frontier = _latex(comparison["stronger_model"])

    claim_text = (
        "The machine-readable release gate "
        + ("passed" if claims.get("release_ready") else "did not pass")
        + ". Fixed-suite substitution was "
        + ("supported" if claims.get("fixed_suite_substitution") else "not supported")
        + ", and cross-task substitution was "
        + ("supported." if claims.get("cross_task_substitution") else "not supported.")
    )
    lines = [
        "% Generated by scripts/govern_bench/render_preprint_results.py; do not edit.",
        r"\begin{table*}[t]",
        r"\centering",
        (
            r"\caption{Preregistered eight-task, four-cell, n=10 substitution "
            f"replication. Workflow {_latex(workflow_id)}, commit "
            rf"\texttt{{{_latex(commit_sha[:12])}}}. TPCA is tokens per correct "
            r"answer and CoP is estimated API cost per passing task.}"
        ),
        r"\label{tab:release-results}",
        r"\begin{tabular}{lrrr}",
        r"\toprule",
        r"System & Correct & TPCA & CoP (USD) \\",
        r"\midrule",
        _metric_row(f"{lower} raw", comparison["smaller_ungoverned"]),
        _metric_row(f"{lower} + Specsmith FULL", comparison["smaller_full"]),
        _metric_row(f"{frontier} raw", comparison["stronger_ungoverned"]),
        _metric_row(f"{frontier} + Specsmith FULL", comparison["stronger_full"]),
        r"\bottomrule",
        r"\end{tabular}",
        r"\end{table*}",
        "",
        r"\paragraph{Preregistered release inference.}",
        (
            f"The lower-tier FULL/frontier-raw TPCA point ratio was "
            f"{float(point['tpca_ratio']):.3f}. Its fixed-suite 95\\% interval was "
            f"{_interval(fixed['tpca_ratio'])}; the task-cluster interval was "
            f"{_interval(clustered['tpca_ratio'])}. The corresponding correctness-"
            "difference intervals were "
            f"{_interval(fixed['pass_rate_difference'], percent=True)} "
            f"and {_interval(clustered['pass_rate_difference'], percent=True)}. "
            f"{claim_text}"
        ),
        "",
    ]
    if coding_summary_path is not None:
        coding_payload = json.loads(coding_summary_path.read_text(encoding="utf-8"))
        coding_comparisons = coding_payload.get("comparisons") or []
        if (
            coding_payload.get("schema") != "governancebench-model-comparison-v1"
            or set(coding_payload.get("tasks") or []) != CODING_TASKS
            or len(coding_comparisons) != 1
        ):
            raise ValueError("coding sensitivity requires one complete six-task comparison")
        coding = coding_comparisons[0]
        coding_inference = coding.get("inference") or {}
        if int(coding_inference.get("minimum_repetitions_per_task") or 0) < 10:
            raise ValueError("coding sensitivity requires at least ten repetitions per task")
        coding_point = coding_inference["point"]
        coding_fixed = coding_inference["fixed_suite_95_ci"]
        coding_clustered = coding_inference["task_cluster_95_ci"]
        coding_claims = coding_inference.get("claims") or {}
        coding_fixed_claim = (
            "supported" if coding_claims.get("fixed_suite_substitution") else "not supported"
        )
        lower_full = coding["smaller_full"]
        frontier_raw = coding["stronger_ungoverned"]
        lines.extend(
            [
                r"\paragraph{Coding-only sensitivity.}",
                (
                    "After excluding deterministic clarification and safety gates, "
                    f"lower-tier FULL passed "
                    f"{round(float(lower_full['pass_rate']) * int(lower_full['runs']))}/"
                    f"{int(lower_full['runs'])} coding cells at "
                    f"{float(lower_full['tokens_per_correct_answer']):,.0f} TPCA; "
                    f"frontier raw passed "
                    f"{round(float(frontier_raw['pass_rate']) * int(frontier_raw['runs']))}/"
                    f"{int(frontier_raw['runs'])} at "
                    f"{float(frontier_raw['tokens_per_correct_answer']):,.0f} TPCA. "
                    f"The TPCA ratio was {float(coding_point['tpca_ratio']):.3f}, with "
                    f"fixed-suite 95\\% interval "
                    f"{_interval(coding_fixed['tpca_ratio'])} and task-cluster interval "
                    f"{_interval(coding_clustered['tpca_ratio'])}. The correctness-"
                    "difference intervals were "
                    f"{_interval(coding_fixed['pass_rate_difference'], percent=True)} "
                    "and "
                    f"{_interval(coding_clustered['pass_rate_difference'], percent=True)}. "
                    f"Coding-only fixed-suite substitution was {coding_fixed_claim}; "
                    "this sensitivity analysis was specified for interpretation after the "
                    "mixed-suite release gate and is not relabelled as the primary endpoint."
                ),
                "",
            ]
        )
    text = "\n".join(lines)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(text, encoding="utf-8")
    return text


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--summary", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--workflow-id", required=True)
    parser.add_argument("--commit-sha", required=True)
    parser.add_argument("--coding-summary", type=Path)
    args = parser.parse_args()
    render_results(
        args.summary,
        args.output,
        workflow_id=args.workflow_id,
        commit_sha=args.commit_sha,
        coding_summary_path=args.coding_summary,
    )
    print(f"Wrote {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
